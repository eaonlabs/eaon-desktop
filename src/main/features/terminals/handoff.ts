import { execFile } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import { promisify } from 'node:util'
import type { TerminalAgentId } from '@shared/terminals'
import { commonDir } from '../ade/git'
import { AGENT_KINDS } from './agentSessions'

const exec = promisify(execFile)

/**
 * Handing a pane's work to another agent: Claude Code got stuck, so Codex
 * (or Gemini, or Cursor) picks it up where it stopped, with everything that
 * was said and done so far.
 *
 * The conversation is written out as a Markdown file in the project
 * (`.eaon/handoffs/`, kept out of git), and the new agent is started on one
 * line telling it to read that file and carry on. A file rather than the
 * whole conversation on the command line: a long session runs to hundreds of
 * kilobytes, and every agent can read a file in its own project.
 *
 * Where the agent keeps a transcript Eaon can read (Claude Code, Codex), the
 * conversation comes from it: what the user asked, what the agent answered,
 * and the commands it ran and files it changed, without the tool output.
 * Any other CLI is handed the text of its terminal instead.
 */

export interface HandoffTurn {
  role: 'user' | 'assistant'
  text: string
  /** What the agent did in this turn, one line each: "ran `npm test`", "edited src/app.ts". */
  actions: string[]
}

/** How much of the conversation goes in the file. Agents read it in one go; this is well inside their context. */
export const HANDOFF_BUDGET = 60_000
/** The last answer is where the work stopped; it's kept whole up to this. */
const LAST_ANSWER_MAX = 6_000
/** Any one message in the conversation section. */
const TURN_MAX = 4_000
/** A command or a path in an action line. */
const ACTION_MAX = 160

const clip = (text: string, max: number): string => (text.length > max ? `${text.slice(0, max).trimEnd()}…` : text)
const oneLine = (text: string): string => text.replace(/\s+/g, ' ').trim()

/** Text Claude Code and Codex put in the user's turn that the user didn't write. */
function harnessText(text: string): boolean {
  const t = text.trimStart()
  return (
    t.startsWith('<command-name>') ||
    t.startsWith('<command-message>') ||
    t.startsWith('<local-command-') ||
    t.startsWith('<environment_context>') ||
    t.startsWith('<user_instructions>') ||
    t.startsWith('<user-prompt-submit-hook>') ||
    t.startsWith('# AGENTS.md') ||
    t.startsWith('Caveat: The messages below were generated by the user while running local commands')
  )
}

/** Drops the notes harnesses tuck into a message (`<system-reminder>…`), keeping what the person wrote. */
function stripNotes(text: string): string {
  // Harness blocks have multi-word tag names (system-reminder, recommended_plugins,
  // environment_context…), which nobody types around their own words.
  return text.replace(/<([a-z]+(?:[-_][a-z]+)+)>[\s\S]*?<\/\1>/g, '').trim()
}

/** One line for what a tool call did, or null for one not worth saying (a todo list, a read of a file). */
export function describeAction(name: string, input: Record<string, unknown>): string | null {
  const str = (key: string): string => (typeof input[key] === 'string' ? oneLine(input[key] as string) : '')
  const file = str('file_path') || str('path') || str('notebook_path')
  switch (name) {
    case 'Bash':
    case 'shell':
    case 'exec_command':
    case 'local_shell': {
      const raw = input.command ?? input.cmd
      const command = Array.isArray(raw) ? raw.map(String).join(' ').replace(/^(?:bash|zsh|sh) -lc /, '') : typeof raw === 'string' ? raw : ''
      return command ? `ran \`${clip(oneLine(command), ACTION_MAX)}\`` : null
    }
    case 'Edit':
    case 'MultiEdit':
    case 'NotebookEdit':
      return file ? `edited ${clip(file, ACTION_MAX)}` : null
    case 'Write':
      return file ? `wrote ${clip(file, ACTION_MAX)}` : null
    case 'apply_patch': {
      const patch = typeof input.input === 'string' ? input.input : typeof input.patch === 'string' ? input.patch : ''
      const files = [...patch.matchAll(/\*\*\* (?:Add|Update|Delete) File: (.+)/g)].map((m) => m[1].trim())
      return files.length ? `edited ${clip(files.join(', '), ACTION_MAX)}` : 'edited files'
    }
    case 'Task':
    case 'Agent':
      return str('description') ? `asked a subagent to ${clip(str('description'), ACTION_MAX)}` : null
    case 'WebFetch':
      return str('url') ? `read ${clip(str('url'), ACTION_MAX)}` : null
    case 'WebSearch':
      return str('query') ? `searched the web for "${clip(str('query'), ACTION_MAX)}"` : null
    case 'Read':
    case 'Grep':
    case 'Glob':
    case 'LS':
    case 'TodoWrite':
    case 'update_plan':
      return null
    default:
      return `used ${name}`
  }
}

/** Adds a turn, or folds it into the one before when the same side spoke again. */
function push(turns: HandoffTurn[], role: HandoffTurn['role'], text: string, actions: string[] = []): void {
  const last = turns.at(-1)
  if (last && last.role === role) {
    if (text) last.text = last.text ? `${last.text}\n\n${text}` : text
    for (const action of actions) if (!last.actions.includes(action)) last.actions.push(action)
    return
  }
  if (!text && actions.length === 0) return
  turns.push({ role, text, actions: [...new Set(actions)] })
}

function lines(jsonl: string): Record<string, unknown>[] {
  const out: Record<string, unknown>[] = []
  for (const line of jsonl.split('\n')) {
    if (!line.trim()) continue
    try {
      const value = JSON.parse(line)
      if (value && typeof value === 'object') out.push(value as Record<string, unknown>)
    } catch {
      // A line cut off mid-write (the agent is still running): skipped.
    }
  }
  return out
}

/** The conversation in a Claude Code transcript (`~/.claude/projects/<slug>/<id>.jsonl`). */
export function claudeTurns(jsonl: string): HandoffTurn[] {
  const turns: HandoffTurn[] = []
  for (const entry of lines(jsonl)) {
    if (entry.isSidechain || entry.isMeta) continue
    const message = entry.message as { content?: unknown } | undefined
    if (entry.type === 'user') {
      const content = message?.content
      const texts =
        typeof content === 'string'
          ? [content]
          : Array.isArray(content)
            ? content.filter((b): b is { type: string; text: string } => b?.type === 'text' && typeof b.text === 'string').map((b) => b.text)
            : []
      // A turn of tool results only is the agent's own work coming back, not the user.
      const text = texts.filter((t) => !harnessText(t)).map(stripNotes).filter(Boolean).join('\n\n')
      if (text) push(turns, 'user', text)
    } else if (entry.type === 'assistant' && Array.isArray(message?.content)) {
      const blocks = message.content as { type?: string; text?: string; name?: string; input?: Record<string, unknown> }[]
      const text = blocks
        .filter((b) => b.type === 'text' && typeof b.text === 'string')
        .map((b) => b.text!.trim())
        .filter(Boolean)
        .join('\n\n')
      const actions = blocks.filter((b) => b.type === 'tool_use' && b.name).map((b) => describeAction(b.name!, b.input ?? {})).filter((a): a is string => Boolean(a))
      push(turns, 'assistant', text, actions)
    }
  }
  return turns
}

/** The conversation in a Codex rollout (`~/.codex/sessions/Y/M/D/rollout-….jsonl`). */
export function codexTurns(jsonl: string): HandoffTurn[] {
  const turns: HandoffTurn[] = []
  const contentText = (content: unknown): string =>
    Array.isArray(content)
      ? content
          .filter((c): c is { text: string } => typeof c?.text === 'string')
          .map((c) => c.text)
          .filter((t) => !harnessText(t))
          .map(stripNotes)
          .filter(Boolean)
          .join('\n\n')
      : ''
  for (const entry of lines(jsonl)) {
    const payload = (entry.payload ?? {}) as Record<string, unknown>
    if (entry.type === 'response_item') {
      if (payload.type === 'message' && payload.role === 'user') {
        const text = contentText(payload.content)
        if (text) push(turns, 'user', text)
      } else if (payload.type === 'message' && payload.role === 'assistant') {
        push(turns, 'assistant', contentText(payload.content))
      } else if (payload.type === 'function_call' || payload.type === 'custom_tool_call' || payload.type === 'local_shell_call') {
        let input: Record<string, unknown> = {}
        if (typeof payload.arguments === 'string') {
          try {
            input = JSON.parse(payload.arguments) as Record<string, unknown>
          } catch {
            input = {}
          }
        } else if (typeof payload.input === 'string') input = { input: payload.input }
        else if (payload.action && typeof payload.action === 'object') input = payload.action as Record<string, unknown>
        const name = typeof payload.name === 'string' ? payload.name : payload.type === 'local_shell_call' ? 'local_shell' : 'tool'
        const action = describeAction(name, input)
        if (action) push(turns, 'assistant', '', [action])
      }
    } else if (entry.type === 'event_msg' && payload.type === 'item_completed') {
      // Newer Codex records its commands and edits here as well (or only here).
      const item = (payload.item ?? {}) as Record<string, unknown>
      if (item.type === 'CommandExecution' && item.command) {
        const action = describeAction('shell', { command: item.command })
        if (action) push(turns, 'assistant', '', [action])
      } else if (item.type === 'FileChange' && item.changes && typeof item.changes === 'object') {
        const files = Array.isArray(item.changes) ? item.changes.map((c) => String((c as { path?: unknown }).path ?? '')).filter(Boolean) : Object.keys(item.changes)
        if (files.length) push(turns, 'assistant', '', [`edited ${clip(files.join(', '), ACTION_MAX)}`])
      }
    }
  }
  return turns
}

/** Readers for the agents whose transcripts Eaon understands. */
const READERS: Partial<Record<TerminalAgentId, (jsonl: string) => HandoffTurn[]>> = {
  claude: claudeTurns,
  codex: codexTurns
}

export const readsTranscript = (agent: TerminalAgentId): boolean => Boolean(READERS[agent])

/** The conversation a pane's agent holds, from its own transcript; null when there isn't one Eaon can read. */
export async function transcriptTurns(agent: TerminalAgentId, cwd: string, sessionId: string | undefined): Promise<HandoffTurn[] | null> {
  const read = READERS[agent]
  if (!read || !sessionId || agent === 'shell') return null
  try {
    const file = (await AGENT_KINDS[agent].conversations(cwd)).get(sessionId)?.file
    if (!file) return null
    const turns = read(await fs.promises.readFile(file, 'utf8'))
    return turns.some((t) => t.role === 'user') ? turns : null
  } catch {
    return null
  }
}

/** What has changed in the project, so the new agent sees the state of the work and not only the talk about it. */
export async function gitSummary(cwd: string): Promise<string | null> {
  const run = async (...args: string[]): Promise<string> => (await exec('git', args, { cwd, timeout: 8000, maxBuffer: 4 * 1024 * 1024 })).stdout.trim()
  try {
    const [branch, status, stat] = await Promise.all([run('branch', '--show-current'), run('status', '--short'), run('diff', 'HEAD', '--stat')])
    const parts = [branch ? `Branch: ${branch}` : null, status ? `\`git status --short\`:\n\n\`\`\`\n${clip(status, 4000)}\n\`\`\`` : 'No uncommitted changes.', stat ? `\`git diff HEAD --stat\`:\n\n\`\`\`\n${clip(stat, 3000)}\n\`\`\`` : null]
    return parts.filter(Boolean).join('\n\n')
  } catch {
    return null
  }
}

export interface HandoffInput {
  fromLabel: string
  toLabel: string
  turns: HandoffTurn[] | null
  /** The pane's terminal text, for an agent without a transcript Eaon reads. */
  screen: string | null
  note: string
  git: string | null
  at: Date
}

function renderTurn(turn: HandoffTurn, fromLabel: string): string {
  const who = turn.role === 'user' ? '### User' : `### ${fromLabel}`
  const body = turn.text ? clip(turn.text, TURN_MAX) : ''
  const actions = turn.actions.length ? turn.actions.map((a) => `- ${a}`).join('\n') : ''
  return [who, body, actions].filter(Boolean).join('\n\n')
}

/** The Markdown the new agent reads. */
export function handoffDocument(input: HandoffInput): string {
  const { fromLabel, toLabel, turns, note } = input
  const head = [
    `# Handoff from ${fromLabel} to ${toLabel}`,
    '',
    `You are taking over work that ${fromLabel} was doing in this project, at the user's request: they want a fresh pair of eyes, from a different model. ${fromLabel} is still open and nothing of its work was undone. Below is the conversation so far, up to where it stopped. Read it, check the current state of the files rather than trusting the conversation alone, and carry on from where it stopped. Don't repeat work that is already done, and don't undo it unless it is wrong.`,
    '',
    `_Written by Eaon on ${input.at.toISOString().slice(0, 16).replace('T', ' ')} UTC._`
  ]
  const sections: string[] = [head.join('\n')]
  if (note.trim()) sections.push(`## Note from the user\n\n${note.trim()}`)

  if (turns && turns.length) {
    const firstAsk = turns.find((t) => t.role === 'user')
    if (firstAsk) sections.push(`## What the user asked first\n\n${clip(firstAsk.text, TURN_MAX)}`)
    const lastAnswer = [...turns].reverse().find((t) => t.role === 'assistant' && t.text)
    // The end of its last turn, where it actually stopped (a long turn's start is narration on the way there).
    if (lastAnswer) sections.push(`## Where ${fromLabel} stopped\n\n${lastAnswer.text.length > LAST_ANSWER_MAX ? `…${lastAnswer.text.slice(-LAST_ANSWER_MAX).trimStart()}` : lastAnswer.text}`)
    if (input.git) sections.push(`## The project now\n\n${input.git}`)

    // Every turn when they fit; otherwise the first two (what the work is)
    // and as many of the latest as fit (where it got to).
    const rendered = turns.map((t) => renderTurn(t, fromLabel))
    const used = sections.join('\n\n').length
    let room = HANDOFF_BUDGET - used
    const total = rendered.reduce((n, r) => n + r.length + 2, 0)
    let body: string[]
    if (total <= room) body = rendered
    else {
      const start = rendered.slice(0, 2)
      room -= start.reduce((n, r) => n + r.length + 2, 0)
      const tail: string[] = []
      for (let i = rendered.length - 1; i >= 2 && room - (rendered[i].length + 2) > 0; i--) {
        tail.unshift(rendered[i])
        room -= rendered[i].length + 2
      }
      const skipped = rendered.length - start.length - tail.length
      body = [...start, `_…${skipped} earlier ${skipped === 1 ? 'message' : 'messages'} left out to keep this short…_`, ...tail]
    }
    sections.push(`## The conversation\n\nEach of ${fromLabel}'s turns lists what it did (commands run, files changed) under its words; their output is left out.\n\n${body.join('\n\n')}`)
  } else {
    if (input.git) sections.push(`## The project now\n\n${input.git}`)
    const screen = (input.screen ?? '').trim()
    sections.push(
      screen
        ? `## ${fromLabel}'s terminal\n\nEaon can't read ${fromLabel}'s own transcript, so this is the text of its terminal, oldest first${screen.length > HANDOFF_BUDGET ? ' (the earliest part left out)' : ''}:\n\n\`\`\`\n${screen.length > HANDOFF_BUDGET ? screen.slice(-HANDOFF_BUDGET) : screen}\n\`\`\``
        : `## ${fromLabel}'s conversation\n\nEaon couldn't read what ${fromLabel} did. Ask the user what they were working on, and look at the project's recent changes.`
    )
  }
  return `${sections.join('\n\n')}\n`
}

/** The file's name: when, from and to, readable in a folder listing. */
export function handoffFileName(from: string, to: string, at: Date): string {
  const slug = (s: string): string => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'agent'
  const stamp = at.toISOString().slice(0, 19).replace('T', '-').replace(/:/g, '')
  return `${stamp}-${slug(from)}-to-${slug(to)}.md`
}

/** Keeps `.eaon/` out of `git status` in every worktree of the repository, as PR reviews do (prReview.ts). */
async function excludeFromGit(cwd: string): Promise<void> {
  try {
    const file = path.join(await commonDir(cwd), 'info', 'exclude')
    const current = fs.existsSync(file) ? await fs.promises.readFile(file, 'utf8') : ''
    if (current.split(/\r?\n/).some((line) => ['.eaon/', '/.eaon/', '.eaon'].includes(line.trim()))) return
    await fs.promises.mkdir(path.dirname(file), { recursive: true })
    await fs.promises.appendFile(file, `${current && !current.endsWith('\n') ? '\n' : ''}# Eaon's agent handoffs\n.eaon/\n`)
  } catch {
    // Not a git repository, or git isn't installed: nothing to keep it out of.
  }
}

/** Writes the handoff into the project and returns where, relative to it. */
export async function writeHandoff(cwd: string, name: string, markdown: string): Promise<string> {
  const dir = path.join(cwd, '.eaon', 'handoffs')
  await fs.promises.mkdir(dir, { recursive: true })
  await fs.promises.writeFile(path.join(dir, name), markdown, 'utf8')
  await excludeFromGit(cwd)
  return path.posix.join('.eaon', 'handoffs', name)
}

/** The one line the new agent starts on. */
export function handoffPrompt(relativeFile: string, fromLabel: string): string {
  return `Read ${relativeFile} first: it is the conversation so far from ${fromLabel} in this project, handed over to you. Then check the files and carry on from where it stopped.`
}
